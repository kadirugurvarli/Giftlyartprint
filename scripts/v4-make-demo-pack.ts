/**
 * Writes a SYNTHETIC-TEST pack (a ray-traced stand-in room, not an AI photo) to exercise the loader and the dry run.
 * It is marked provenance.kind = "synthetic-test", so it can never be sent to a paid model.
 *   npx tsx scripts/v4-make-demo-pack.ts [dir]      (default validation-output/v4-demo-pack, git-ignored)
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import {assertOutputIgnored} from "../lib/mockup-v3/validation/runner";
import type {PackManifest} from "../lib/mockup-v4/pack";
import {landscapeArt} from "../tests/helpers/scenes";
import {syntheticRoom} from "../tests/helpers/rooms";

(async()=>{
  const dir=path.resolve(process.argv[2] ?? "validation-output/v4-demo-pack");
  assertOutputIgnored(dir);
  const s=syntheticRoom({withPlant:true,scale:2,origin:"owned-photo"});
  const art=landscapeArt(1500,2000,3);
  const png=(i:{width:number;height:number;data:Uint8ClampedArray})=>sharp(Buffer.from(i.data.buffer,i.data.byteOffset,i.data.byteLength),{raw:{width:i.width,height:i.height,channels:4}}).removeAlpha().png().toBuffer();
  fs.writeFileSync(path.join(dir,"room.png"),await png(s.image));
  fs.writeFileSync(path.join(dir,"artwork.png"),await png(art));
  const manifest:PackManifest={
    schemaVersion:1,id:"synthetic-demo-pack",roomImage:"room.png",artworkImage:"artwork.png",
    room:{...s.room,id:"synthetic-demo-room"},
    provenance:{kind:"synthetic-test",rightsCleared:true,licence:"generated by this repository's test helpers; no third-party content",emptyWallConfirmed:true},
    artwork:{origin:"synthetic-test",customer:false,licence:"generated by this repository's test helpers"},
    frame:{mouldingWidthCm:2.4,mountWidthCm:3.5,frameDepthCm:3,mouldingColour:[66,48,34],mountColour:[238,233,222],description:"a dark walnut-brown wooden moulding with a cream mount"}
  };
  fs.writeFileSync(path.join(dir,"manifest.json"),JSON.stringify(manifest,null,2));
  console.log("wrote synthetic-test pack to",dir);
})();
